"""
Publication-style LaTeX tables (booktabs + threeparttable) from results/*.json.

  python paper_tables.py --data_dir "C:/.../mlearn-master/mlearn-master/data"

Writes paper_figures/tables.tex containing:
  tab:dataset   dataset statistics
  tab:accuracy  energy and force MAE, all models and elements
  tab:relforce  relative force error
  tab:cost      model size and computational cost

Required in the Overleaf preamble:
  \\usepackage{booktabs}
  \\usepackage{threeparttable}
"""
import argparse
import json
from collections import defaultdict
from pathlib import Path

import numpy as np

ap = argparse.ArgumentParser()
ap.add_argument("--data_dir", required=True)
ap.add_argument("--results", default="results")
ap.add_argument("--out", default="paper_figures")
a = ap.parse_args()

ELEMENT_ORDER = ["Cu", "Ni", "Li", "Mo", "Si", "Ge"]
LATTICE = {"Cu": "fcc", "Ni": "fcc", "Li": "bcc", "Mo": "bcc",
           "Si": "diamond", "Ge": "diamond"}
MODEL_ORDER = ["schnet", "dimenetpp", "painn", "mace", "chgnet_zs", "chgnet_ft"]
NAMES = {"schnet": "SchNet", "dimenetpp": "DimeNet++", "painn": "PaiNN", "mace": "MACE",
         "chgnet_zs": "CHGNet-ZS", "chgnet_ft": "CHGNet-FT"}

NO_TRAINING = {"chgnet_zs"}     # deterministic, no seeds -> never marked "single run"

res = [json.load(open(p)) for p in sorted(Path(a.results).glob("*.json"))]
res = [r for r in res if r.get("train_fraction", 1.0) == 1.0]
if not res:
    raise SystemExit("No full-data results found.")
groups = defaultdict(list)
for r in res:
    groups[(r["element"], r["model"])].append(r)
elements = [e for e in ELEMENT_ORDER if any(k[0] == e for k in groups)]
models = [m for m in MODEL_ORDER if any(k[1] == m for k in groups)]
multi_seed = any(len(v) > 1 for v in groups.values())
n_seeds = max(len(v) for v in groups.values())

# ---------------------------------------------------------------- dataset stats
stats = {}
for el in elements:
    d_tr = json.load(open(Path(a.data_dir) / el / "training.json"))
    d_te = json.load(open(Path(a.data_dir) / el / "test.json"))
    n_at = [d["num_atoms"] for d in d_tr + d_te]
    f_te = np.concatenate([np.ravel(d["outputs"]["forces"]) for d in d_te])
    stats[el] = {"n_train": len(d_tr), "n_test": len(d_te),
                 "atoms": f"{min(n_at)}--{max(n_at)}",
                 "mean_f": float(np.abs(f_te).mean())}


def values(el, m, key, scale=1.0):
    runs = groups.get((el, m), [])
    return np.array([r[key] for r in runs]) * scale if runs else None


def fmt_cell(v, digits, bold, mark_single):
    if v is None:
        return "--"
    if len(v) > 1:
        s = f"{v.mean():.{digits}f}\\,$\\pm$\\,{v.std(ddof=1):.{digits}f}"
    else:
        s = f"{v[0]:.{digits}f}"
    if bold:
        s = f"\\textbf{{{s}}}"
    if len(v) == 1 and mark_single:
        s += r"\tnote{a}"
    return s


def row_cells(el, key, digits, scale_fn=lambda el: 1.0):
    """Bold the best model only if its mean +/- std overlaps with no other model."""
    st = {}
    for m in models:
        v = values(el, m, key, scale_fn(el))
        if v is not None:
            st[m] = (v.mean(), v.std(ddof=1) if len(v) > 1 else 0.0)
    order = sorted(st, key=lambda m: st[m][0])
    best = None
    if len(order) == 1:
        best = order[0]
    elif len(order) > 1:
        m1, s1 = st[order[0]]
        if all(m1 + s1 < st[o][0] - st[o][1] for o in order[1:]):
            best = order[0]
    return [fmt_cell(values(el, m, key, scale_fn(el)), digits, m == best,
                     multi_seed and m not in NO_TRAINING)
            for m in models]


def notes():
    n = [r"\item Bold: lowest error, where its mean\,$\pm$\,standard deviation does not "
         r"overlap with that of any other model."]
    if "chgnet_zs" in models or "chgnet_ft" in models:
        n.append(r"\item CHGNet-ZS: pretrained universal model without training on these data; "
                 r"energies shifted by one per-atom constant fitted on the training set. "
                 r"CHGNet-FT: fine-tuned on each training set.")
    if multi_seed:
        n.append(rf"\item Mean\,$\pm$\,standard deviation over {n_seeds} random seeds "
                 r"(different validation splits and initialisations).")
        if any(len(groups.get((e, m), [])) == 1 for e in elements for m in models
               if m not in NO_TRAINING):
            n.append(r"\item[a] Single training run (seed 0).")
    return n


tex = [r"% ---- generated by paper_tables.py ----",
       r"% Preamble: \usepackage{booktabs} \usepackage{threeparttable}", ""]

# ---- Table: dataset
tex += [r"\begin{table}[t]", r"\centering",
        r"\caption{Overview of the mlearn benchmark dataset~\cite{zuo2020performance}. "
        r"Each element contains AIMD snapshots, strained (elastic) bulk cells, "
        r"surfaces and vacancy configurations. $\langle|F|\rangle$ is the mean "
        r"absolute force component in the test set (eV\,\AA$^{-1}$); "
        r"Atoms is the range of atoms per cell. $N_\mathrm{train}$ includes the 10\,\% "
        r"of structures held out for validation and early stopping.}",
        r"\label{tab:dataset}", r"\small", r"\setlength{\tabcolsep}{4pt}",
        r"\begin{tabular}{llrrcc}", r"\toprule",
        r"Element & Lattice & $N_\mathrm{train}$ & $N_\mathrm{test}$ & Atoms & "
        r"$\langle|F|\rangle$ \\", r"\midrule"]
for el in elements:
    s = stats[el]
    tex.append(f"{el} & {LATTICE[el]} & {s['n_train']} & {s['n_test']} & "
               f"{s['atoms']} & {s['mean_f']:.2f} \\\\")
tex += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]

# ---- Table: accuracy (energy panel above force panel; double column if > 4 models)
nm = len(models)
acc_wide = nm > 4
tex += [r"\begin{table*}[t]" if acc_wide else r"\begin{table}[t]", r"\centering",
        r"\caption{Test-set mean absolute errors of energies and forces for all models and elements.}",
        r"\label{tab:accuracy}", r"\small", r"\begin{threeparttable}",
        r"\begin{tabular}{l" + "c" * nm + "}", r"\toprule",
        "Element & " + " & ".join(NAMES[m] for m in models) + r" \\", r"\midrule",
        rf"\multicolumn{{{nm + 1}}}{{l}}{{\textit{{Energy MAE (meV\,atom$^{{-1}}$)}}}} \\"]
for el in elements:
    tex.append(f"{el} & " + " & ".join(row_cells(el, "energy_mae_meV_atom", 2)) + r" \\")
tex += [r"\midrule",
        rf"\multicolumn{{{nm + 1}}}{{l}}{{\textit{{Force MAE (meV\,\AA$^{{-1}}$)}}}} \\"]
for el in elements:
    tex.append(f"{el} & " + " & ".join(row_cells(el, "force_mae_eV_A", 1, lambda _: 1000.0)) + r" \\")
tex += [r"\bottomrule", r"\end{tabular}", r"\begin{tablenotes}\footnotesize"] + notes() + \
       [r"\end{tablenotes}", r"\end{threeparttable}",
        r"\end{table*}" if acc_wide else r"\end{table}", ""]

# ---- Table: relative force error
wide = len(models) > 4
tex += [r"\begin{table*}[t]" if wide else r"\begin{table}[t]", r"\centering",
        r"\caption{Relative force error, MAE$/\langle|F|\rangle$ (\%), which allows "
        r"comparison across elements with different force magnitudes.}",
        r"\label{tab:relforce}", r"\begin{threeparttable}",
        r"\begin{tabular}{l" + "c" * nm + "}", r"\toprule",
        "Element & " + " & ".join(NAMES[m] for m in models) + r" \\", r"\midrule"]
for el in elements:
    cells = row_cells(el, "force_mae_eV_A", 1, lambda e: 100.0 / stats[e]["mean_f"])
    tex.append(f"{el} & " + " & ".join(cells) + r" \\")
tex += [r"\bottomrule", r"\end{tabular}", r"\begin{tablenotes}\footnotesize"] + notes() + \
       [r"\end{tablenotes}", r"\end{threeparttable}",
        r"\end{table*}" if wide else r"\end{table}", ""]

# ---- Table: cost
tex += [r"\begin{table}[t]", r"\centering",
        r"\caption{Model size and computational cost, averaged over all elements "
        r"and seeds, on an NVIDIA RTX~3060 GPU. Train: wall time per training run; "
        r"Epochs: epochs until the stopping criterion was met; Infer.: test-set "
        r"inference time per structure including data handling, intended for relative "
        r"comparison only.}",
        r"\label{tab:cost}", r"\small", r"\setlength{\tabcolsep}{3pt}",
        r"\begin{tabular}{lrrrr}", r"\toprule",
        r"Model & Params & Train (min) & Epochs & Infer.\ (ms) \\",
        r"\midrule"]
for m in models:
    runs = [r for k, v in groups.items() if k[1] == m for r in v]
    n_par = runs[0].get("n_params")
    t_tr = [r["train_time_s"] / 60 for r in runs if "train_time_s" in r]
    eps = [r["epochs_run"] for r in runs if "epochs_run" in r]
    t_in = np.mean([1000 * r["test_time_s"] / r["n_test"] for r in runs])
    par = f"{n_par:,}" if n_par else "--"
    tr = f"{np.mean(t_tr):.1f}" if t_tr else "--"
    ep = f"{np.mean(eps):.0f}" if eps else "--"
    tex.append(f"{NAMES[m]} & {par} & {tr} & {ep} & {t_in:.2f} \\\\")
tex += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]

out = Path(a.out)
out.mkdir(exist_ok=True)
(out / "tables.tex").write_text("\n".join(tex), encoding="utf-8")
print("\n".join(tex))
print(f"\nSaved {out / 'tables.tex'}")